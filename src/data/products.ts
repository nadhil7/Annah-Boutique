// Distribute each category folder's photos across that category's products.
// Every downloaded image appears in at least one PDP gallery, while the first
// image remains the product-card image.
const groupedProducts = new Map<string, Product[]>();
for (const product of products) {
  const group = groupedProducts.get(product.category) ?? [];
  group.push(product);
  groupedProducts.set(product.category, group);
}
for (const [category, group] of groupedProducts) {
  const photos = productPhotosByCategory[category] ?? [];
  if (!photos.length) continue;
  const perProduct = Math.floor(photos.length / group.length);
  const extras = photos.length % group.length;
  let cursor = 0;
  group.forEach((product, index) => {
    const take = perProduct + (index < extras ? 1 : 0);
    product.images = photos.slice(cursor, cursor + take);
    cursor += take;
  });
}

export const productsMap: Record<string, Product> = Object.fromEntries(
  products.map((p) => [p.id, p])
);

export const productsBySlug: Record<string, Product> = Object.fromEntries(
  products.map((p) => [p.slug, p])
);
